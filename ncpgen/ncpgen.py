#!/usr/bin/env python3
"""ncpgen: an open NCP generator for the Exynos 990 NPU (PORT-32; dossier/npu-compiler.md section 10,
docs/format/). Pure Python, our own code: it writes the NCP that Samsung's NPUC 1.36.1.a writes for the same
lowered network, part by part, and is checked byte for byte against NPUC run as an oracle (npuc-local.sh).

  ncpgen.py gen <net.json|model.tflite|lowered.json> <out.ncp> [--quant 1|3] [--allow-none] [--grelu fixed|robust|npuc]
                [--fix-npuc]
        the NCP for a model (ncpgen/npunet.py lowers it first unless it is already lowered). The activation table:
        fixed (default: the corrected one, = ncp-grelu-patch.py auto, the tables that ran bit-exact on the NPU),
        robust (group 0 copied to the four groups), npuc (NPUC's own bytes, with its defect: docs/format/grelu.md).
        --fix-npuc: consistent DMA strides where NPUC's are suspect (outputs of 3/5/7 channels, a conv after a widened
        pool: docs/format/frame.md section 9; G until the NPU runs them); otherwise NPUC's bytes.
  ncpgen.py check [--grelu npuc|fixed|robust] <variant dir>...
        each dir as written by npuc-local.sh (lowered.json + NPUC's net.ncp): every part generated from lowered.json
        and compared with NPUC's: streams, intrinsics, weight blocks, then the whole file (when frame.py can assemble
        it; with the parts the generator cannot make yet taken from NPUC's file, so each part is judged alone).
        Default: NPUC's GReLU bytes (byte-for-byte comparison); prints one line per dir and a total.
  ncpgen.py corpus <dir> [--jobs N]
        compile the regression corpus (CORPUS below) with NPUC into <dir>/<name>/ (npuc-local.sh): the variants every
        part is checked on. Vendor-generated bytes: <dir> must be under output/ or a scratch folder.

Parts (each its own module in this directory, written from oracle sweeps and disassembly):
  stream.py   group_streams(low) -> [isa bytes per group]            (the CMDQ instruction streams)
  grelu.py    grelu_regs(layer, quant_mode, fixed) -> [(addr, value)] (the activation table, used by stream.py)
  weights.py  weight_blocks(low) -> [WEIGHT block bytes]
  frame.py    intrinsics(low) -> [bytes per group]; frame(low, streams, intrinsics, weights) -> the NCP
"""
import hashlib
import importlib
import json
import os
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ORACLE = os.path.join(os.path.dirname(HERE), "oracle")  # npuc-variant.py, npuc-local.sh (the NPUC oracle)
sys.path.insert(0, HERE)  # the parts and npunet.py are siblings

# The regression corpus: (name, npuc-variant.py arguments, npuc-local.sh options). Family F1 (one conv, optionally a
# pool) first, then chains. Our own seeded weights.
CORPUS = []


def _c(name, spec, opts=""):
    CORPUS.append((name, spec, opts))


for k in (1, 3, 5, 7):
    _c("f1-k%d" % k, "--in 16,16,8 --conv 8,%d" % k)
for co in (1, 2, 4, 16, 32):
    _c("f1-cout%d" % co, "--in 16,16,8 --conv %d,3" % co)
for ci in (1, 3, 4, 16, 32):
    _c("f1-cin%d" % ci, "--in 16,16,%d --conv 8,3" % ci)
for h, w in ((8, 8), (12, 12), (16, 24), (20, 20), (32, 32), (7, 9), (5, 13)):
    _c("f1-hw%dx%d" % (h, w), "--in %d,%d,8 --conv 8,3" % (h, w))
_c("f1-s2", "--in 16,16,8 --conv 8,3,2")
_c("f1-valid", "--in 16,16,8 --conv 8,3,1,valid")
_c("f1-s2valid", "--in 16,16,8 --conv 8,3,2,valid")
_c("f1-k1x3", "--in 16,16,8 --conv 8,1 --kw 3")
_c("f1-k3x1", "--in 16,16,8 --conv 8,3 --kw 1")
_c("f1-none", "--in 16,16,8 --conv 8,3,1,same,none", "--allow-none")
_c("f1-q3", "--in 16,16,8 --conv 8,3", "--quant 3")
_c("f1-q3-none", "--in 16,16,8 --conv 8,3,1,same,none", "--quant 3 --allow-none")
_c("f1-oscale", "--in 16,16,8 --conv 8,3 --oscale 0.01 --ozp 5")
_c("f1-zero-w", "--in 16,16,8 --conv 8,3 --weights zero")
_c("f1-seed7", "--in 16,16,8 --conv 8,3 --seed 7")
_c("f1-maxpool", "--in 16,16,8 --conv 8,3 --pool max,2")
_c("f1-avgpool", "--in 16,16,8 --conv 8,3 --pool avg,2")
_c("f1-q3-maxpool", "--in 16,16,8 --conv 8,3 --pool max,2", "--quant 3")
_c("f2-convconv", "--in 16,16,8 --conv 8,3 --conv 8,3")
_c("f2-tiny", "--in 16,16,8 --conv 8,3 --pool max,2 --conv 8,3 --oscale 0.001953125")
_c("f2-convconv-c16", "--in 16,16,8 --conv 16,3 --conv 8,1")
_c("f3-hw64", "--in 64,64,8 --conv 8,3")
_c("f3-c64", "--in 16,16,64 --conv 64,3")


def load_part(name):
    try:
        return importlib.import_module(name)
    except ModuleNotFoundError as e:
        if e.name == name:
            return None
        raise


def lower_model(path, quant=1, allow_none=False):
    import npunet
    d = json.load(open(path)) if path.endswith(".json") else None
    if d is not None and d.get("format") == "npu-lowered/1":
        return d
    return npunet.load_model(path, quant, False, allow_none)


# --- reading NPUC's NCP into the same parts ------------------------------------------------------------------------
def cut(ncp):
    h = struct.unpack_from("<32I", ncp, 0)
    avo, avc, mvo, mvc, gvo, gvc = h[10:16]
    body = h[17]
    av = [struct.unpack_from("<4I", ncp, avo + 16 * i) for i in range(avc)]
    mv = [struct.unpack_from("<8I", ncp, mvo + 32 * i) for i in range(mvc)]
    gv = [struct.unpack_from("<10I", ncp, gvo + 40 * i) for i in range(gvc)]
    streams = [ncp[body + g[8]:body + g[8] + g[9]] for g in gv]
    intr = [ncp[body + g[6]:body + g[6] + g[7]] for g in gv]
    weights = [ncp[av[m[7]][1]:av[m[7]][1] + av[m[7]][3]] for m in mv if m[0] == 7]
    return {"streams": streams, "intrinsics": intr, "weights": weights}


def first_diff(a, b):
    for i in range(min(len(a), len(b))):
        if a[i] != b[i]:
            return i
    return min(len(a), len(b)) if len(a) != len(b) else None


def cmp_list(mine, ref, unit):
    if mine is None:
        return "-", False
    if len(mine) != len(ref):
        return "count %d/%d" % (len(mine), len(ref)), False
    bad = []
    for i, (m, r) in enumerate(zip(mine, ref)):
        o = first_diff(m, r)
        if o is not None:
            bad.append("%s%d@%#x%s" % (unit, i, o, "" if len(m) == len(r) else "(len %d/%d)" % (len(m), len(r))))
    return ("ok" if not bad else " ".join(bad[:3])), not bad


GRELU = {"fixed": True, "robust": "robust", "npuc": False}


def generate(low, grelu="fixed", ref_parts=None, fix_npuc=False):
    """the NCP's parts from our modules; a part whose module is missing (or refuses this network) is taken from
    ref_parts when given (check mode), else the generation fails. grelu: "fixed" (the corrected table, = what
    ncp-grelu-patch.py auto writes: the NCPs that ran bit-exact), "robust" (group 0 copied to all four groups), or
    "npuc" (NPUC's own bytes, defect included)"""
    parts, notes = {}, []
    st, fr, wt = load_part("stream"), load_part("frame"), load_part("weights")
    calls = (("streams", st, "group_streams", {"fixed": GRELU[grelu]}), ("intrinsics", fr, "intrinsics", {}),
             ("weights", wt, "weight_blocks", {}))
    for key, mod, fn, kw in calls:
        val = None
        if mod is not None and hasattr(mod, fn):
            try:
                val = getattr(mod, fn)(low, **kw)
            except Exception as e:  # a part that cannot handle this network yet says so
                notes.append("%s: %s: %s" % (key, type(e).__name__, e))
        parts[key] = val
    whole = None
    if fr is not None and hasattr(fr, "frame"):
        use = {k: (v if v is not None else (ref_parts or {}).get(k)) for k, v in parts.items()}
        if all(v is not None for v in use.values()):
            try:
                whole = fr.frame(low, use["streams"], use["intrinsics"], use["weights"], fix_npuc=fix_npuc)
            except Exception as e:
                notes.append("frame: %s: %s" % (type(e).__name__, e))
    return parts, whole, notes


def cmd_check(dirs, grelu="npuc"):
    tot = {"streams": 0, "intrinsics": 0, "weights": 0, "file": 0, "pure": 0}
    n = 0
    for d in dirs:
        lp, np_ = os.path.join(d, "lowered.json"), os.path.join(d, "net.ncp")
        if not (os.path.isfile(lp) and os.path.isfile(np_)):
            print("%-24s skipped (no lowered.json/net.ncp)" % os.path.basename(d.rstrip("/")))
            continue
        n += 1
        low = json.load(open(lp))
        ref = open(np_, "rb").read()
        rp = cut(ref)
        parts, whole, notes = generate(low, grelu=grelu, ref_parts=rp)
        res = []
        pure = True
        for key, unit in (("streams", "g"), ("intrinsics", "g"), ("weights", "w")):
            s, ok = cmp_list(parts[key], rp[key], unit)
            tot[key] += ok
            pure &= ok
            res.append("%s %s" % (key[:5], s))
        if whole is None:
            res.append("file -")
            pure = False
        else:
            o = first_diff(whole, ref)
            okf = o is None
            tot["file"] += okf
            pure &= okf
            res.append("file %s" % ("ok" if okf else "@%#x (len %d/%d)" % (o, len(whole), len(ref))))
        tot["pure"] += pure
        print("%-24s %s%s" % (os.path.basename(d.rstrip("/")), " | ".join(res), "  EXACT" if pure else ""))
        for x in notes:
            print("    note: " + x)
    print("ncpgen check: %d variants: streams %d, intrinsics %d, weights %d, whole file %d (with NPUC's parts where "
          "ours are missing), generated entirely by us and exact: %d" % (n, tot["streams"], tot["intrinsics"],
                                                                        tot["weights"], tot["file"], tot["pure"]))
    return 0 if n and tot["pure"] == n else 2


def cmd_gen(src, out, quant, allow_none, grelu, fix_npuc=False):
    low = lower_model(src, quant, allow_none)
    parts, whole, notes = generate(low, grelu=grelu, fix_npuc=fix_npuc)
    for x in notes:
        print("ncpgen: " + x)
    if whole is None:
        missing = [k for k, v in parts.items() if v is None] + ([] if load_part("frame") else ["frame"])
        print("ncpgen: FAIL: cannot generate this network yet (missing: %s)" % ", ".join(missing))
        return 2
    open(out, "wb").write(whole)
    print("ncpgen: PASS %s %d B sha256 %s (GReLU table: %s)" % (out, len(whole), hashlib.sha256(whole).hexdigest(), grelu + (", strides fixed" if fix_npuc else "")))
    return 0


def cmd_corpus(d, jobs):
    os.makedirs(d, exist_ok=True)
    procs, fails = [], []
    todo = list(CORPUS)

    def start(name, spec, opts):
        vj = os.path.join(d, name + ".json")
        subprocess.run([sys.executable, "-I", os.path.join(ORACLE, "npuc-variant.py"), vj] + spec.split(), check=True,
                       stdout=subprocess.DEVNULL)
        return subprocess.Popen(["bash", os.path.join(ORACLE, "npuc-local.sh"), vj, os.path.join(d, name)] + opts.split(),
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)

    while todo or procs:
        while todo and len(procs) < jobs:
            name, spec, opts = todo.pop(0)
            procs.append((name, start(name, spec, opts)))
        name, p = procs.pop(0)
        out = p.communicate()[0]
        last = out.strip().splitlines()[-1] if out.strip() else ""
        print("%-24s %s" % (name, last.replace(os.path.abspath(os.path.join(d, name)) + "/", "")))
        if p.returncode:
            fails.append(name)
    print("ncpgen corpus: %d variants, %d failed%s" % (len(CORPUS), len(fails), (": " + " ".join(fails)) if fails else ""))
    return 0


def main():
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    cmd = a.pop(0)

    def flag(n):
        if n in a:
            a.remove(n)
            return True
        return False

    def opt(n, dflt):
        if n in a:
            i = a.index(n)
            v = a[i + 1]
            del a[i:i + 2]
            return v
        return dflt

    g = opt("--grelu", None)
    if g is not None and g not in GRELU:
        sys.exit("ncpgen: --grelu fixed|robust|npuc")
    if cmd == "check":
        # check compares against NPUC's own bytes, so NPUC's own GReLU table unless told otherwise
        sys.exit(cmd_check(a, grelu=g or "npuc"))
    if cmd == "gen" and len(a) >= 2:
        q = int(opt("--quant", 1))
        alln, fx = flag("--allow-none"), flag("--fix-npuc")
        sys.exit(cmd_gen(a[0], a[1], q, alln, g or "fixed", fx))
    if cmd == "corpus" and a:
        j = int(opt("--jobs", 4))
        sys.exit(cmd_corpus(a[0], j))
    sys.exit(__doc__)


if __name__ == "__main__":
    main()
