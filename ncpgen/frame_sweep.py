#!/usr/bin/env python3
"""The oracle sweeps behind frame.py (docs/format/frame.md): the variant families, compiled with NPUC
(npuc-local.sh, up to 6 at once), then judged by frame.py check. Our own seeded networks (npuc-variant.py).

  frame_sweep.py list [family...]                  print the specs ("name | npuc-variant args | npuc-local opts")
  frame_sweep.py run <outroot> [family...] [--jobs N]   compile what is missing into <outroot>/<family>/<name>/
  frame_sweep.py check <outroot> [family...]       frame.py check over the compiled dirs
  frame_sweep.py policy <variant dir>...           frame.npuc_policy against NPUC's prints in each log.txt (node
                                                   tile counts, strata, every tiled-memory estimate; frame.md 6.10)

Families: ch (C 1..33), co (cout 1..33), hw (H, W 1..64), mix (channels, chains, big shapes), sq (square and long
shapes, the IM vector rule), tile (where NPUC starts tiling), dim (the 255 limit), chain (big chains), rnd1, rnd2
(random chains, seeds 20261121 and 777), split (the IFM split), widen (pools that keep a column), pstore (pool-last
partial stores), io17 (more than 16 DMAs), edge (1x1 and very wide tensors), cluster (IFM clustering, DMA batches,
up to 512 output channels), rnd3 (random wide-channel chains, seed 4242), tiled (plans NPUC splits into tiles: by
height, width, both, SRAM; with pools and chains), tiled2 (tile size limits, stratum chaining, mixed tiled and untiled
blocks), wstream (plans that stream their weights), direct (tiled strata whose first conv reads the tile directly), nfu
(tall pools: NFU command pieces, not tiles), wlive (ring sizes 1..7: the WEIGHT live range), ringc (rings with Cout
not a multiple of 16), h48 (tile heights of SRAM-tiled convs), spill (NPUC's copy when no allocation fits), tiling2 (around final-chains' tiling misses). Compiled NCPs and logs hold vendor-generated bytes: <outroot> must be
git-ignored ($NCPGEN_WORK/sweep/frame).
"""
