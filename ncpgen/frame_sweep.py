def _random(seed, n, hw, chans, nls, couts, ks, prefix, base_seed):
    rng = random.Random(seed)
    L = []
    for i in range(n):
        H, W, C = rng.randint(*hw), rng.randint(*hw), rng.choice(chans)
        spec = "--in %d,%d,%d --seed %d" % (H, W, C, base_seed + i)
        h, w, nconv = H, W, 0
        for k in range(rng.choice(nls)):
            if rng.random() < 0.35 and h >= 2 and w >= 2:
                pk, ps = rng.choice([2, 2, 3]), rng.choice([1, 2, 2, 3])
                pad = rng.choice(["valid", "valid", "same"])
                if pad == "valid" and (h < pk or w < pk):
                    pad = "same"
                spec += " --pool %s,%d,%d,%s" % (rng.choice(["max", "max", "avg"]), pk, ps, pad)
                h, w = ((h - pk) // ps + 1, (w - pk) // ps + 1) if pad == "valid" else (-(-h // ps), -(-w // ps))
            else:
                co, kk, s = rng.choice(couts), rng.choice(ks), rng.choice([1, 1, 1, 2])
                pad = rng.choice(["same", "same", "valid"])
                if pad == "valid" and (h < kk or w < kk):
                    pad = "same"
                spec += " --conv %d,%d,%d,%s,%s" % (co, kk, s, pad, rng.choice(["relu", "relu", "none"]))
                r = rng.random()
                spec += " --weights zero" if r < 0.1 else (" --weights impulse:0,0,0,0,9" if r < 0.2 else "")
                h, w = ((h - kk) // s + 1, (w - kk) // s + 1) if pad == "valid" else (-(-h // s), -(-w // s))
                nconv += 1
            if h < 1 or w < 1:
                break
        if not nconv:
            spec += " --conv 8,3"
        L.append("%s%03d | %s | --allow-none%s" % (prefix, i, spec, " --quant 3" if rng.random() < 0.2 else ""))
    return L


def fam_rnd1():
    rng = random.Random(20261121)
    L = []
    for i in range(160):
        H, W, C = rng.randint(3, 72), rng.randint(3, 72), rng.randint(1, 40)
        spec = "--in %d,%d,%d --seed %d" % (H, W, C, i)
        h, w = H, W
        for k in range(rng.choice([1, 1, 2, 2, 3, 4])):
            if (rng.random() < 0.3 and k > 0) or (rng.random() < 0.1):
                pk = rng.choice([2, 2, 3])
                ps = rng.choice([1, 2, pk])
                pad = rng.choice(["valid", "valid", "same"])
                if pad == "valid" and (h < pk or w < pk):
                    continue
                spec += " --pool %s,%d,%d,%s" % (rng.choice(["max", "max", "avg"]), pk, ps, pad)
                h, w = ((h - pk) // ps + 1, (w - pk) // ps + 1) if pad == "valid" else (-(-h // ps), -(-w // ps))
            else:
                co = rng.choice([1, 2, 3, 4, 5, 8, 8, 8, 12, 16, 16, 24, 32, 33, 40, 48])
                kk = rng.choice([1, 3, 3, 3, 5])
                s = rng.choice([1, 1, 1, 2])
                pad = rng.choice(["same", "same", "valid"])
                if pad == "valid" and (h < kk or w < kk):
                    pad = "same"
                spec += " --conv %d,%d,%d,%s,%s" % (co, kk, s, pad, rng.choice(["relu", "relu", "relu", "none"]))
                if rng.random() < 0.2:
                    spec += " --weights zero" if rng.random() < 0.5 else " --weights impulse:0,0,0,0,7"
                h, w = ((h - kk) // s + 1, (w - kk) // s + 1) if pad == "valid" else (-(-h // s), -(-w // s))
            if h < 1 or w < 1:
                break
        if "--conv" not in spec:
            spec += " --conv 8,3"
        L.append("rnd%03d | %s | %s" % (i, spec, "--allow-none" + (" --quant 3" if rng.random() < 0.2 else "")))
    return L


